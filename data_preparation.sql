SELECT date, 
 (CASE WHEN EXTRACT(MONTH FROM date) IN (1) THEN 'Jan'
      WHEN EXTRACT(MONTH FROM date) IN (2) THEN 'Feb'
      WHEN EXTRACT(MONTH FROM date) IN (3) THEN 'Mar'
      WHEN EXTRACT(MONTH FROM date) IN (4) THEN 'April'
      WHEN EXTRACT(MONTH FROM date) IN (5) THEN 'May'
      WHEN EXTRACT(MONTH FROM date) IN (6) THEN 'June'
      WHEN EXTRACT(MONTH FROM date) IN (7) THEN 'July'
      WHEN EXTRACT(MONTH FROM date) IN (8) THEN 'Aug'
      WHEN EXTRACT(MONTH FROM date) IN (9) THEN 'Sep'
      WHEN EXTRACT(MONTH FROM date) IN (10) THEN 'Oct'
      WHEN EXTRACT(MONTH FROM date) IN (11) THEN 'Nov'
      WHEN EXTRACT(MONTH FROM date) IN (12) THEN 'Dec' END) AS month, 
      
  (CASE WHEN EXTRACT(MONTH FROM date) IN (1) THEN 1
      WHEN EXTRACT(MONTH FROM date) IN (2) THEN 2
      WHEN EXTRACT(MONTH FROM date) IN (3) THEN 3
      WHEN EXTRACT(MONTH FROM date) IN (4) THEN 4
      WHEN EXTRACT(MONTH FROM date) IN (5) THEN 5
      WHEN EXTRACT(MONTH FROM date) IN (6) THEN 6
      WHEN EXTRACT(MONTH FROM date) IN (7) THEN 7
      WHEN EXTRACT(MONTH FROM date) IN (8) THEN 8
      WHEN EXTRACT(MONTH FROM date) IN (9) THEN 9
      WHEN EXTRACT(MONTH FROM date) IN (10) THEN 10
      WHEN EXTRACT(MONTH FROM date) IN (11) THEN 11
      WHEN EXTRACT(MONTH FROM date) IN (12) THEN 12 END) AS month_num
FROM Ad_Performance.Ad_Performance_Table